"""Write docs/python-coverage.md from the validated seed bank (not from hand-kept numbers).  Usage (from backend/):  python -m tools.python_coverage_report"""

from __future__ import annotations

from collections import Counter, defaultdict
from pathlib import Path

from app.services.python_practice import bank
from app.services.python_practice.syllabus import MIN_QUESTIONS_PER_TOPIC, UNITS

OUT = Path(__file__).resolve().parents[2] / "docs" / "python-coverage.md"


def main() -> int:
    valid, rejected = bank.build_valid_seed_bank()
    by_topic: dict[str, list[dict]] = defaultdict(list)
    for q in valid:
        by_topic[q["topic_id"]].append(q)
    lines = ["# Python practice: syllabus coverage matrix", "", "Generated by `python -m tools.python_coverage_report` from the validated seed bank. Do not edit by hand.", ""]
    ver = Counter(q["review_status"] for q in valid)
    lines += [f"* Units: {len(UNITS)}, topics: {sum(len(u.topics) for u in UNITS)}, **questions: {len(valid)}** (rejected by validation: {len(rejected)}).",
              f"* Interactions: " + ", ".join(f"{k} {v}" for k, v in sorted(Counter(q['interaction'] for q in valid).items())) + ".",
              f"* Formats: " + ", ".join(f"{k} {v}" for k, v in sorted(Counter(q['format'] for q in valid).items())) + ".",
              f"* Verification: **{ver['execution_verified']} execution-verified** (snippet was run in the isolated runner and its output matched), **{ver['reference_verified']} reference-verified** "
              f"(expected outputs computed from a reference solution that an independent solution agreed with on every test, and that passed in the runner), "
              f"**{ver['manual_review']} manual-review only** (theory questions with no executable check; they need subject-expert sign-off).", ""]
    gaps: list[str] = []
    for u in UNITS:
        qs = [q for t in u.topics for q in by_topic[t.id]]
        lv = Counter(q["difficulty"] for q in qs)
        lines += [f"## Unit {u.code}: {u.title}", "", f"{len(qs)} questions (easy {lv['easy']}, medium {lv['medium']}, hard {lv['hard']}).", "",
                  "| Topic | Syllabus bullet(s) | Qs | E/M/H | Exercise types | Machine-verified | Status |", "|---|---|---|---|---|---|---|"]
        for t in u.topics:
            rows = by_topic[t.id]
            d = Counter(q["difficulty"] for q in rows)
            fm = Counter(q["format"] for q in rows)
            mv = sum(1 for q in rows if q["review_status"] != "manual_review")
            status = "ready" if len(rows) >= MIN_QUESTIONS_PER_TOPIC else ("partial" if rows else "missing")
            lines.append(f"| {t.title} | {t.covers or t.title} | {len(rows)} | {d['easy']}/{d['medium']}/{d['hard']} | {', '.join(f'{k} {v}' for k, v in sorted(fm.items()))} | {mv}/{len(rows)} | {status} |")
            if len(rows) < MIN_QUESTIONS_PER_TOPIC:
                gaps.append(f"{t.title}: {len(rows)} question(s)")
            if rows and mv == 0:
                gaps.append(f"{t.title}: every question is manual-review only (no executed or cross-checked exercise)")
        thin = [d for d in ("hard",) if lv[d] < 3]
        if thin:
            gaps.append(f"Unit {u.code}: only {lv['hard']} hard question(s)")
        lines.append("")
    lines += ["## Gaps", ""] + ([f"* {g}" for g in gaps] if gaps else ["* None against the minimum rules."])
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(valid)} questions, {len(gaps)} gap notes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
